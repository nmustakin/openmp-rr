#!/bin/bash
# Write Makefile.rr for HeCBench OpenMP applications on AMD GPUs.
#
# The NVIDIA Makefile.rr files retargeted HeCBench's Makefile.aomp to nvptx64.
# On AMD, Makefile.aomp already targets amdgcn, so Makefile.rr only includes it,
# pins the GPU architecture, and adds the record-replay offload flags (as in
# Device.GetCompileOptions): mandatory offload, offload LTO, embedded bitcode.
#
# Usage: make_rr_amd.sh <HeCBench root> <arch, e.g. gfx906> [app-omp ...]
# Without application names, writes Makefile.rr for every wrapper in
# hecbench/ and hecbench2/ (their SRC directories).
set -euo pipefail
root=$1; arch=$2; shift 2
here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
if [ $# -eq 0 ]; then
  set -- $(grep -ho "src/[A-Za-z0-9_.-]*-omp'" "$here"/*.py "$here"/../hecbench2/*.py \
           | sed "s|src/||; s|'||" | sort -u)
fi
written=0
for app in "$@"; do
  dir=$root/src/$app
  if [ ! -f "$dir/Makefile.aomp" ]; then
    echo "skip $app: no Makefile.aomp" >&2
    continue
  fi
  cat > "$dir/Makefile.rr" <<EOF
# Generated by record-replay/RR/benchmarks/hecbench/make_rr_amd.sh.
override ARCH = $arch
include Makefile.aomp
CFLAGS += -fopenmp-offload-mandatory -foffload-lto
LDFLAGS += -foffload-lto -Wl,--embed-bitcode
EOF
  written=$((written + 1))
done
echo "wrote $written Makefile.rr"
